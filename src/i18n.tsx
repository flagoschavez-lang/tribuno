const DICTS: Record<Lang, Dict> = { es: ES, en: EN };

const CATEGORY_KEYS: Record<Category, string> = {
  overview: 'cat.overview',
  stocks: 'cat.stocks',
  crypto: 'cat.crypto',
  indices: 'cat.indices',
  forex: 'cat.forex',
  futures: 'cat.futures',
  bonds: 'cat.bonds',
  etfs: 'cat.etfs',
};

const REGION_KEYS: Record<Region, string> = {
  global: 'reg.global',
  us: 'reg.us',
  europe: 'reg.europe',
  asia: 'reg.asia',
  apac: 'reg.apac',
  latam: 'reg.latam',
};

interface I18nContextValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  toggleLang: () => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
  catLabel: (id: Category) => string;
  regionLabel: (id: Region) => string;
  headingFor: (id: Category) => string;
  locale: string;
}

const I18nContext = createContext<I18nContextValue>({
  lang: 'es',
  setLang: () => undefined,
  toggleLang: () => undefined,
  t: (key) => ES[key] ?? key,
  catLabel: (id) => ES[CATEGORY_KEYS[id]] ?? id,
  regionLabel: (id) => ES[REGION_KEYS[id]] ?? id,
  headingFor: (id) => ES[`heading.${id}`] ?? id,
  locale: 'es-ES',
});

export function useI18n(): I18nContextValue {
  return useContext(I18nContext);
}

const STORAGE_KEY = 'tribuno.lang.v1';

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    try { const stored = window.localStorage.getItem(STORAGE_KEY); if (stored === 'es' || stored === 'en') return stored; } catch { /* ignore */ }
    return 'es';
  });

  useEffect(() => {
    document.documentElement.lang = lang;
    try { window.localStorage.setItem(STORAGE_KEY, lang); } catch { /* ignore */ }
  }, [lang]);

  const setLang = useCallback((next: Lang) => setLangState(next), []);
  const toggleLang = useCallback(() => setLangState((current) => (current === 'es' ? 'en' : 'es')), []);

  const t = useCallback((key: string, vars?: Record<string, string | number>) => {
    const dict = DICTS[lang] ?? ES;
    let value = dict[key] ?? ES[key] ?? key;
    if (vars) for (const [name, replacement] of Object.entries(vars)) value = value.replace(new RegExp(`\\{${name}\\}`, 'g'), String(replacement));
    return value;
  }, [lang]);

  const value = useMemo<I18nContextValue>(() => ({
    lang,
    setLang,
    toggleLang,
    t,
    catLabel: (id) => t(CATEGORY_KEYS[id]),
    regionLabel: (id) => t(REGION_KEYS[id]),
    headingFor: (id) => t(`heading.${id}`),
    locale: lang === 'en' ? 'en-US' : 'es-ES',
  }), [lang, setLang, toggleLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}
